def test_http_source_reads_the_stored_explanation(
    stub: Stub,  # noqa: F811
    explained: dict[str, bytes],
) -> None:
    stub.routes = {path: (200, body) for path, body in explained.items()}
    source = HttpAlertSource(stub.url)
    (alert,) = source.list_alerts(AlertQuery()).items

    explanation = source.get_explanation(alert.alert_id)

    assert explanation is not None
    assert explanation.alert_id == alert.alert_id and explanation.status == "ready"
    assert explanation.source == "template" and explanation.text.startswith("[SIMULATION]")
    detail = alert_detail(alert, explanation)
    assert detail.explanation == explanation.text
    assert detail.explanation_note is not None
    assert detail.explanation_note.startswith("Deterministic text from the alert's fields")


def test_no_explanation_is_not_an_error(stub: Stub) -> None:  # noqa: F811
    """404: the API runs without the audit chain, or the alert has none."""
    assert HttpAlertSource(stub.url).get_explanation("A-unknown") is None
    assert PlaybackAlertSource(RUN).get_explanation("A-20190314T1705Z-1") is None
    snapshot = SnapshotAlertSource(str(RUN / "status.json"))  # never read for explanations
    assert snapshot.get_explanation("A-x") is None
    fallback = FallbackAlertSource(HttpAlertSource(stub.url), PlaybackAlertSource(RUN))
    assert fallback.get_explanation("A-unknown") is None


def _explanation(alert: Alert, **update: Any) -> ExplanationStatus:
    base = {
        "status": "ready",
        "alert_id": alert.alert_id,
        "language": "en",
        "alert_payload_sha256": "0" * 64,
        "source": "template",
        "text": "Alert: suspected leak.\nCandidate pipe: p1.",
        "generator": None,
        "generated_at": "2026-10-18T05:44:10Z",
        "fallback_reason": None,
        "record": {"seq": 3, "hash": "a" * 64},
    }
    return ExplanationStatus.model_validate({**base, **update})


def test_explanation_note_says_how_the_text_was_produced() -> None:
    (alert,) = PlaybackAlertSource(RUN).list_alerts(AlertQuery()).items

    llm = _explanation(alert, source="llm", generator="watsonx/granite-3-8b-instruct")
    assert explanation_note(llm) == (
        "Generated by watsonx/granite-3-8b-instruct, 2026-10-18 05:44:10 UTC."
    )
    fallback = _explanation(alert, fallback_reason="narrator_error: timeout")
    assert "Language model not used: narrator_error: timeout." in explanation_note(fallback)
    pending = _explanation(alert, status="pending", generated_at=None)
    assert explanation_note(pending).startswith("Being generated")


def test_an_explanation_of_another_alert_is_not_shown() -> None:
    (alert,) = PlaybackAlertSource(RUN).list_alerts(AlertQuery()).items
    other = _explanation(alert, alert_id="A-other")

    detail = alert_detail(alert, other)

    assert (detail.explanation, detail.explanation_note) == (EXPLANATION_UNAVAILABLE, None)


def test_app_shows_the_explanation_in_the_assistant(
    stub: Stub,  # noqa: F811
    explained: dict[str, bytes],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    testing = pytest.importorskip("streamlit.testing.v1")
    stub.routes = {path: (200, body) for path, body in explained.items()}
    monkeypatch.setenv("SENTINEL_DASHBOARD_API_URL", stub.url)
    text = json.loads(next(b for p, b in explained.items() if p.endswith("/explanation")))["text"]


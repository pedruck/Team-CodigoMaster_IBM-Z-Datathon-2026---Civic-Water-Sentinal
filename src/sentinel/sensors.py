"""Sensor registry: the set of sensor IDs a window must contain (``SENTINEL_SENSOR_REGISTRY``).

- ``config/sensors.battledim.json`` — **official** BattLeDIM L-Town registry, owned and
  generated by the data owner (``python -m sentinel.data.build_registry``). IDs are the
  network elements: ``n1``…``n769``, ``p227``, ``p235``, ``PUMP_1``, ``T1`` (``docs/data.md``).
- ``config/sensors.provisional.json`` — placeholder IDs (``P01``…), default for development
  and tests only.

Registry order is the canonical sensor order (array order for models).

Optional ``limits`` give the physically valid range of each sensor kind, in the registry's
units (inclusive). A reading outside it is refused (422 ``reading_out_of_range``): it is a
broken sensor or a bad client, never a leak. The official registry copies the data owner's
cleaning ranges from the data ``MANIFEST.json`` (``cleaning.valid_ranges``).
"""

import json
from dataclasses import dataclass
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field, model_validator

from sentinel.schemas.windows import SensorId

KINDS = ("pressure", "flow", "tank_level")


class Limit(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    min: float
    max: float

    @model_validator(mode="after")
    def _ordered(self) -> "Limit":
        if not self.min < self.max:
            raise ValueError(f"limit min ({self.min}) must be below max ({self.max})")
        return self


class SensorRegistryFile(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    provisional: bool
    note: str = ""
    pressure: list[SensorId] = Field(min_length=1)
    flow: list[SensorId] = Field(default_factory=list)
    tank_level: list[SensorId] = Field(default_factory=list)
    # Optional {"pressure": "m", ...}; shown in /v1/status when present.
    units: dict[str, str] | None = None
    limits: dict[str, Limit] | None = None

    @model_validator(mode="after")
    def _known_limit_kinds(self) -> "SensorRegistryFile":
        unknown = sorted(set(self.limits or {}) - set(KINDS))
        if unknown:
            raise ValueError(f"limits for unknown sensor kinds {unknown}; expected {KINDS}")
        return self

    @model_validator(mode="after")
    def _unique_ids(self) -> "SensorRegistryFile":
        ids = [*self.pressure, *self.flow, *self.tank_level]
        duplicates = sorted({i for i in ids if ids.count(i) > 1})
        if duplicates:
            raise ValueError(f"duplicate sensor ids: {duplicates}")
        return self


@dataclass(frozen=True, slots=True)
class SensorRegistry:
    pressure: tuple[str, ...]
    flow: tuple[str, ...]
    tank_level: tuple[str, ...]
    provisional: bool
    source: str
    units: dict[str, str] | None = None
    limits: dict[str, tuple[float, float]] | None = None

    @classmethod
    def load(cls, path: Path) -> "SensorRegistry":
        data = SensorRegistryFile.model_validate(json.loads(path.read_text(encoding="utf-8")))
        return cls(
            pressure=tuple(data.pressure),
            flow=tuple(data.flow),
            tank_level=tuple(data.tank_level),
            provisional=data.provisional,
            source=str(path),
            units=data.units,
            limits=(
                {kind: (lim.min, lim.max) for kind, lim in data.limits.items()}
                if data.limits
                else None
            ),
        )

    @property
    def counts(self) -> dict[str, int]:
        return {
            "pressure": len(self.pressure),
            "flow": len(self.flow),
            "tank_level": len(self.tank_level),
        }
